// The chapter designer publishes this small file; every game and the treasure
// book consume the same allocation without rewriting the game engines.
try {
  const allocationUrl = new URL('./chapter-allocations.json', import.meta.url);
  allocationUrl.searchParams.set('read', Date.now().toString(36));
  const response = await fetch(allocationUrl, {cache:'no-store'});
  if (response.ok) {
    const data = await response.json();
    for (const [game, prizes] of Object.entries(data.games || {})) {
      if (kits[game] && Array.isArray(prizes) && prizes.length === 6 && prizes.every(id => typeof id === 'string' && items[id])) kits[game].prizes = [...prizes];
    }
  }
} catch (_) { /* Offline play keeps the built-in chapter prizes. */ }
