import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const src = fs.readFileSync(new URL('../world/items/model.js', import.meta.url), 'utf8');
const sandbox = {window: {}, globalThis: {}};
sandbox.globalThis = sandbox;
vm.runInNewContext(src, sandbox);
const model = sandbox.PennyFeverInventoryModel;
const empty = model.entries({demoCoins: 12, pennyPacks: 0, playTickets: 1, paperInventory: {version: 1, items: {}}});
const penny = empty.find(i => i.id === 'everyday-penny');
const pack = empty.find(i => i.id === 'five-penny-stack');
assert.equal(penny.kind, 'currency');
assert.equal(penny.quantity, 12);
assert.equal(pack.kind, 'currency');
assert.equal(pack.owned, true);
assert.equal(pack.quantity, 0);
const parked = model.entries({demoCoins: 3, pennyPacks: 4, playTickets: 0, paperInventory: {version: 1, items: {}}});
assert.equal(parked.find(i => i.id === 'everyday-penny').quantity, 3);
assert.equal(parked.find(i => i.id === 'five-penny-stack').quantity, 4);
assert.match(parked.find(i => i.id === 'five-penny-stack').status, /4 packs/);
console.log('PASS: Treasures lists loose pennies and 5-packs from the live purse, with no purse prize required.');
